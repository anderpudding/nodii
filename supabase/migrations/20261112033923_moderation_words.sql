create table public.reserved_words (word text primary key);

create table public.banned_words (
  word text primary key,
  match text not null check (match in ('contains', 'exact')),
  lang text not null
);

alter table public.reserved_words enable row level security;
alter table public.banned_words enable row level security;

revoke all on table public.reserved_words, public.banned_words from public, anon, authenticated;
grant select on table public.reserved_words, public.banned_words to authenticated;

create policy "read reserved words" on public.reserved_words for select to authenticated using (true);
create policy "read banned words" on public.banned_words for select to authenticated using (true);

