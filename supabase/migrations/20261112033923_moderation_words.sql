  ('a$shole', 'contains', 'en'),
  ('orgasmus', 'contains', 'en'),
  ('snatch', 'contains', 'en'),
  ('tnnd', 'contains', 'en'),
  ('sucker', 'exact', 'en');

create function public.normalize_text(t text)
returns text language sql immutable strict set search_path = '' as $$
  select lower(normalize(t, NFKC));
$$;

create function public.text_is_allowed(t text)
returns boolean language sql stable strict set search_path = '' as $$
  with input as (
    select public.normalize_text(t) as normalized
  )
  select not exists (
    select 1 from public.banned_words w
    where (w.match = 'contains' and strpos(input.normalized, w.word) > 0)
       or (w.match = 'exact' and w.word = any(regexp_split_to_array(input.normalized, '[[:space:][:punct:]]+')))
  )
  from input;
$$;

create function public.text_is_reserved(t text)
returns boolean language sql stable strict set search_path = '' as $$
  select exists (select 1 from public.reserved_words where word = public.normalize_text(t));
$$;

-- 인증된 본인에게만 양도 제한을 안내한다. 다른 사용자의 보류 내역은 노출하지 않는다.
create function public.handle_available(p_handle text)
returns text language plpgsql stable security definer set search_path = '' as $$
begin
  if auth.uid() is null then
    raise exception 'authentication required';
  end if;

  if p_handle is null or p_handle !~ '^[a-z][a-z0-9_.]{2,19}$'
     or p_handle like '%..%' or p_handle like '%.' then
    return 'invalid';
  elsif public.text_is_reserved(p_handle) then
    return 'reserved';
  elsif not public.text_is_allowed(p_handle) then
    return 'banned';
  elsif exists (select 1 from public.social_profiles where handle = p_handle and user_id <> auth.uid()) then
    return 'taken';
  elsif exists (
    select 1 from public.handle_holds
    where handle = p_handle and available_at > now() and released_by is distinct from auth.uid()
  ) then
    return 'held';
  end if;
  return 'ok';
end;
$$;

create function social_private.social_profiles_guard()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  -- BEFORE 트리거는 INSERT RLS 검사보다 먼저 실행된다.
  if current_setting('role') = 'authenticated' and new.user_id is distinct from auth.uid() then
    raise insufficient_privilege;
  end if;
  if public.text_is_reserved(new.handle) or public.text_is_reserved(new.nickname) then
    raise exception 'reserved';
  end if;
  if not public.text_is_allowed(new.handle) or not public.text_is_allowed(new.nickname)
     or not public.text_is_allowed(new.bio) then
    raise exception 'banned';
  end if;

  if tg_op = 'UPDATE' and new.handle = old.handle then
    return new;
  end if;
  if tg_op = 'UPDATE' and old.handle_changed_at > now() - interval '30 days' then
    raise exception 'handle_cooldown';
  end if;

  -- 같은 새 핸들을 고르는 요청끼리 순서대로 보류 상태를 확인한다.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('social_handle:' || new.handle, 0));
  if exists (
    select 1 from public.handle_holds
    where handle = new.handle and available_at > now() and released_by is distinct from new.user_id
  ) then
    raise exception 'handle_held';
  end if;

  if tg_op = 'UPDATE' then
    insert into public.handle_holds (handle, released_by, available_at)
    values (old.handle, old.user_id, now() + interval '30 days')
    on conflict (handle) do update
      set released_by = excluded.released_by, available_at = excluded.available_at;
    new.handle_changed_at := now();
  end if;
  return new;
end;
$$;

revoke execute on function public.normalize_text(text), public.text_is_allowed(text),
  public.text_is_reserved(text), public.handle_available(text) from public, anon, authenticated;
grant execute on function public.normalize_text(text), public.text_is_allowed(text),
  public.text_is_reserved(text), public.handle_available(text) to authenticated;
revoke execute on function social_private.social_profiles_guard() from public, anon, authenticated;

create trigger social_profiles_guard
  before insert or update of handle, nickname, bio on public.social_profiles
  for each row execute function social_private.social_profiles_guard();
